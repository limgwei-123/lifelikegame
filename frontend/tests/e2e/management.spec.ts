import { test, expect } from '@playwright/test';

test.skip(process.env.E2E_DISPOSABLE_API !== '1', 'Requires an isolated disposable backend');

test('real management: goal and scoring CRUD, immutable scores, reward redemption and history', async ({ page, request }, testInfo) => {
  test.setTimeout(180_000);
  const api = process.env.E2E_API_URL || 'http://localhost:8001';
  const email = `management-${Date.now()}@example.com`, password = 'Review-only-Password2026!';
  expect((await request.post(`${api}/auth/signup`, { data: { email, password } })).status()).toBe(201);
  const auth = await request.post(`${api}/auth/login`, { data: { email, password } }); expect(auth.ok()).toBeTruthy();
  const headers = { Authorization: `Bearer ${(await auth.json()).access_token}` };
  const get = async (path: string) => { const r = await request.get(api + path, { headers }); expect(r.ok()).toBeTruthy(); return r.json(); };
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/login');
  await page.getByLabel('邮箱', { exact: true }).fill(email); await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('button', { name: '添加任务', exact: true })).toBeEnabled();
  const visit = async (name: string, add?: string) => {
    await page.getByRole('tab', { name: '我的', exact: true }).click();
    // The My tab retains its nested route when switching tabs.
    if (await page.getByRole('button', { name: '返回我的', exact: true }).isVisible()) await page.getByRole('button', { name: '返回我的', exact: true }).click();
    await page.getByRole('button', { name, exact: true }).click();
    if (add) await expect(page.getByRole('button', { name: add, exact: true })).toBeEnabled();
    else await expect(page.getByRole('button', { name: '刷新管理列表' })).toBeEnabled();
  };
  const dialog = (name: string) => page.getByRole('dialog', { name, exact: true });
  const save = async (name: string, kind: string) => {
    await dialog(name).getByRole('button', { name: `保存${kind}`, exact: true }).click();
    await expect(dialog(name)).toBeHidden();
    await expect(page.getByRole('button', { name: '刷新管理列表' })).toBeEnabled();
  };
  const remove = async (title: string, kind: string) => {
    await page.getByRole('button', { name: `删除 ${title}`, exact: true }).click();
    await dialog(`删除${kind}`).getByRole('button', { name: '确认删除', exact: true }).click();
    await expect(dialog(`删除${kind}`)).toBeHidden();
    await expect(page.getByRole('button', { name: '刷新管理列表' })).toBeEnabled();
  };
  await visit('目标', '添加目标');
  await page.getByRole('button', { name: '添加目标', exact: true }).click();
  await dialog('添加目标').getByLabel('目标名称', { exact: true }).fill('运动');
  await dialog('添加目标').getByLabel('当前进度（选填）', { exact: true }).fill('每周 1 次');
  await dialog('添加目标').getByLabel('期望进度（选填）', { exact: true }).fill('每周 3 次');
  await save('添加目标', '目标');
  const goal = (await get('/goals'))[0]; expect(goal.current_value).toBe('每周 1 次');
  await page.getByRole('button', { name: '编辑 运动', exact: true }).click();
  await dialog('编辑目标').getByLabel('当前进度（选填）', { exact: true }).fill('');
  await save('编辑目标', '目标'); expect((await get('/goals'))[0].current_value).toBeNull();
  await visit('评分方案', '添加评分方案');
  await page.getByRole('button', { name: '添加评分方案', exact: true }).click();
  await dialog('添加评分方案').getByLabel('评分方案名称', { exact: true }).fill('运动评分');
  await dialog('添加评分方案').getByLabel('等级 1 名称', { exact: true }).fill('完成');
  await dialog('添加评分方案').getByLabel('等级 1 分数', { exact: true }).fill('5');
  await save('添加评分方案', '评分方案');
  await page.getByRole('tab', { name: '首页', exact: true }).click();
  const createTask = async (title: string) => {
    await expect(page.getByRole('button', { name: '添加任务', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: '添加任务', exact: true }).click();
    await dialog('添加任务').getByLabel('任务名称', { exact: true }).fill(title);
    await dialog('添加任务').getByRole('button', { name: '运动', exact: true }).click();
    await dialog('添加任务').getByRole('button', { name: '运动评分', exact: true }).click();
    await dialog('添加任务').getByRole('button', { name: '添加任务', exact: true }).click();
    await expect(dialog('添加任务')).toBeHidden();
    await expect(page.getByRole('button', { name: '添加任务', exact: true })).toBeEnabled();
  };
  await createTask('旧评分任务');
  await visit('评分方案', '添加评分方案');
  await page.getByRole('button', { name: '编辑 运动评分', exact: true }).click();
  await dialog('编辑评分方案').getByLabel('等级 1 分数', { exact: true }).fill('9');
  await save('编辑评分方案', '评分方案');
  await page.getByRole('tab', { name: '首页', exact: true }).click();
  await createTask('新评分任务');
  await visit('评分方案', '添加评分方案'); await remove('运动评分', '评分方案');
  await page.getByRole('tab', { name: '首页', exact: true }).click();
  await expect(page.getByRole('button', { name: '添加任务', exact: true })).toBeEnabled();
  await page.getByRole('checkbox', { name: '完成 旧评分任务', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: '完成 旧评分任务', exact: true })).toBeChecked();
  expect((await get('/users/me')).current_value).toBe(5);
  await expect(page.getByRole('button', { name: '添加任务', exact: true })).toBeEnabled();
  await page.getByRole('checkbox', { name: '完成 新评分任务', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: '完成 新评分任务', exact: true })).toBeChecked();
  expect((await get('/users/me')).current_value).toBe(14);
  await visit('奖励', '添加奖励');
  await page.getByRole('button', { name: '添加奖励', exact: true }).click();
  await dialog('添加奖励').getByLabel('奖励名称', { exact: true }).fill('看电影');
  await dialog('添加奖励').getByLabel('所需积分', { exact: true }).fill('3');
  await save('添加奖励', '奖励');
  const reward = (await get('/rewards'))[0];
  await expect(page.getByTestId('management-balance')).toHaveText('14');
  await page.getByRole('button', { name: '兑换 看电影', exact: true }).click();
  const redeemPath = `**/workflows/rewards/${reward.id}/redeem`;
  await page.route(redeemPath, route => route.fulfill({ status: 409, json: { code: 'CONFLICT', message: 'Not Enough Points' } }));
  await dialog('兑换奖励').getByRole('button', { name: '确认兑换', exact: true }).click();
  await expect(dialog('兑换奖励').getByRole('alert')).toContainText('积分不足');
  await expect(page.getByTestId('management-balance')).toHaveText('14');
  expect((await get('/redemptions')).length).toBe(0);
  await page.unroute(redeemPath);
  let calls = 0;
  page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith(`/workflows/rewards/${reward.id}/redeem`)) calls++; });
  await dialog('兑换奖励').getByRole('button', { name: '确认兑换', exact: true }).click();
  await expect(dialog('兑换奖励')).toBeHidden();
  await expect(page.getByTestId('management-balance')).toHaveText('11'); expect(calls).toBe(1);
  await expect(page.getByText('已兑换', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '编辑 看电影', exact: true }).click();
  await dialog('编辑奖励').getByLabel('奖励名称', { exact: true }).fill('改名后的电影');
  await dialog('编辑奖励').getByLabel('所需积分', { exact: true }).fill('0');
  await save('编辑奖励', '奖励');
  await remove('改名后的电影', '奖励');
  await page.getByRole('button', { name: '兑换记录', exact: true }).click();
  await expect(page.getByText('看电影', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: '添加奖励', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '兑换记录', exact: true }).click();
  await expect(page.getByText('看电影', { exact: true })).toBeVisible();
  await visit('积分记录');
  await expect(page.getByText('兑换：看电影', { exact: true })).toBeVisible();
  await expect(page.getByTestId('management-balance')).toHaveText('11');
  expect((await get('/point_ledgers')).reduce((sum: number, entry: { delta: number }) => sum + entry.delta, 0)).toBe(11);
  await page.screenshot({ path: testInfo.outputPath('points-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: testInfo.outputPath('points-phone-dark.png'), fullPage: true });
  await visit('目标', '添加目标'); await remove('运动', '目标');
  expect(await get('/goals')).toHaveLength(0); expect((await get('/users/me')).current_value).toBe(11);
  await expect(page.getByRole('tab')).toHaveCount(3);
  expect(errors).toEqual([]);
});
