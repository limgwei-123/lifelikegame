import { test, expect } from '@playwright/test';

test.skip(process.env.E2E_DISPOSABLE_API !== '1', 'Requires an isolated disposable backend');
test('real profile, timezone, device appearance and password revocation', async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  const api = process.env.E2E_API_URL || 'http://localhost:8001';
  const email = `account-${Date.now()}@example.com`, password = 'Review-only-Password2026!', nextPassword = 'Updated-only-Password2026!';
  expect((await request.post(`${api}/auth/signup`, { data: { email, password } })).status()).toBe(201);
  const auth = await request.post(`${api}/auth/login`, { data: { email, password } }); expect(auth.ok()).toBeTruthy();
  const oldHeaders = { Authorization: `Bearer ${(await auth.json()).access_token}` };
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ colorScheme: 'light' });
  await page.goto('/login');
  await page.getByLabel('邮箱', { exact: true }).fill(email); await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('tab', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: '个人资料', exact: true }).click();
  let profile = page.getByRole('dialog', { name: '个人资料', exact: true });
  await profile.getByLabel('昵称（选填）', { exact: true }).fill('林间冒险者');
  await profile.getByRole('button', { name: '头像：阅读', exact: true }).click();
  await profile.getByRole('button', { name: '洛杉矶', exact: true }).click();
  await profile.getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(profile).toBeHidden();
  await expect(page.getByTestId('profile-name')).toHaveText('林间冒险者');
  await expect(page.getByTestId('profile-timezone')).toHaveText('America/Los_Angeles');
  await expect(page.getByTestId('page-我的').getByTestId('avatar-book')).toBeVisible();
  await page.reload();
  await expect(page.getByTestId('profile-name')).toHaveText('林间冒险者');
  await expect(page.getByTestId('profile-timezone')).toHaveText('America/Los_Angeles');
  const me = await request.get(`${api}/users/me`, { headers: oldHeaders }); expect(me.ok()).toBeTruthy();
  expect((await me.json()).avatar_key).toBe('book');
  const progress = await request.get(`${api}/progress`, { headers: oldHeaders }); expect(progress.ok()).toBeTruthy();
  const day = await progress.json(); expect(day.timezone).toBe('America/Los_Angeles');
  await page.getByRole('tab', { name: '首页', exact: true }).click();
  await expect(page.getByRole('button', { name: day.today, exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('tab', { name: '我的', exact: true }).click();
  await page.getByRole('button', { name: '个人资料', exact: true }).click();
  profile = page.getByRole('dialog', { name: '个人资料', exact: true });
  await profile.getByLabel('昵称（选填）', { exact: true }).fill('a'.repeat(31));
  await profile.getByLabel('时区', { exact: true }).fill('Not/AZone');
  await profile.getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(profile.getByText('昵称最多 30 个字。')).toBeVisible();
  await expect(profile.getByText('请选择有效的时区，例如 Asia/Kuala_Lumpur。')).toBeVisible();
  await profile.getByLabel('昵称（选填）', { exact: true }).fill('未保存的修改');
  await profile.getByLabel('时区', { exact: true }).fill('America/Los_Angeles');
  await page.route('**/users/me', route => route.request().method() === 'PATCH'
    ? route.fulfill({ status: 500, json: { code: 'UNAVAILABLE' } }) : route.continue());
  await profile.getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(profile.getByRole('alert').filter({ hasText: '服务暂时不可用' })).toBeVisible();
  await expect(page.getByTestId('profile-name')).toHaveText('林间冒险者');
  await profile.getByRole('button', { name: '关闭', exact: true }).click();
  await page.unroute('**/users/me');
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  let appearance = page.getByRole('dialog', { name: '外观设置', exact: true });
  await appearance.getByRole('button', { name: '深色', exact: true }).click();
  await expect(page.getByTestId('page-我的')).toHaveCSS('background-color', 'rgb(16, 23, 34)');
  await appearance.getByRole('button', { name: '紫色', exact: true }).click();
  await expect(appearance.getByRole('button', { name: '紫色', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await appearance.getByRole('button', { name: '关闭', exact: true }).click();
  await page.reload();
  await expect(page.getByTestId('page-我的')).toHaveCSS('background-color', 'rgb(16, 23, 34)');
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  appearance = page.getByRole('dialog', { name: '外观设置', exact: true });
  await expect(appearance.getByRole('button', { name: '紫色', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await appearance.getByRole('button', { name: '跟随系统', exact: true }).click();
  await page.emulateMedia({ colorScheme: 'light' });
  await expect(page.getByTestId('page-我的')).toHaveCSS('background-color', 'rgb(245, 247, 252)');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.getByTestId('page-我的')).toHaveCSS('background-color', 'rgb(16, 23, 34)');
  // Exercise the actual web adapter's failure boundary, not just a fake store.
  await page.evaluate(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) {
      if (key === 'lifelikegame_appearance_v1') throw new DOMException('Storage unavailable', 'QuotaExceededError');
      return original.call(this, key, value);
    };
    (window as Window & { restoreAppearanceStorage?: () => void }).restoreAppearanceStorage = () => { Storage.prototype.setItem = original; };
  });
  await appearance.getByRole('button', { name: '橙色', exact: true }).click();
  await expect(appearance.getByText('无法保存外观设置，请重试。')).toBeVisible();
  await expect(appearance.getByRole('button', { name: '紫色', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.evaluate(() => { (window as Window & { restoreAppearanceStorage?: () => void }).restoreAppearanceStorage?.(); });
  await appearance.getByRole('button', { name: '浅色', exact: true }).click();
  await appearance.getByRole('button', { name: '绿色', exact: true }).click();
  await appearance.getByRole('button', { name: '关闭', exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath('account-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath('account-phone.png'), fullPage: true });
  await page.getByRole('button', { name: '外观设置', exact: true }).click();
  appearance = page.getByRole('dialog', { name: '外观设置', exact: true });
  await appearance.getByRole('button', { name: '深色', exact: true }).click();
  await appearance.getByRole('button', { name: '紫色', exact: true }).click();
  await page.waitForTimeout(350); // Capture the settled RN Modal fade.
  await page.screenshot({ path: testInfo.outputPath('appearance-phone.png'), fullPage: true });
  await appearance.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '修改密码', exact: true }).click();
  const changing = page.getByRole('dialog', { name: '修改密码', exact: true });
  let writes = 0; page.on('request', r => { if (r.url().endsWith('/auth/change-password')) writes++; });
  await changing.getByLabel('当前密码', { exact: true }).fill(password);
  await changing.getByLabel('新密码', { exact: true }).fill(nextPassword);
  await changing.getByLabel('确认新密码', { exact: true }).fill('mismatch');
  await changing.getByRole('button', { name: '更新密码', exact: true }).click();
  await expect(changing.getByText('两次输入的新密码不一致。')).toBeVisible(); expect(writes).toBe(0);
  await changing.getByLabel('确认新密码', { exact: true }).fill(nextPassword);
  await changing.getByLabel('当前密码', { exact: true }).fill('wrong-password');
  await changing.getByRole('button', { name: '更新密码', exact: true }).click();
  await expect(changing.getByText('当前密码不正确。')).toBeVisible();
  await expect(changing.getByLabel('新密码', { exact: true })).toHaveValue(nextPassword);
  await changing.getByLabel('当前密码', { exact: true }).fill(password);
  await changing.getByRole('button', { name: '更新密码', exact: true }).click();
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible();
  await expect(page.getByText('密码已更新，请重新登录。')).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('lifelikegame_access_token'))).toBeNull();
  expect((await request.get(`${api}/users/me`, { headers: oldHeaders })).status()).toBe(401);
  expect((await request.post(`${api}/auth/login`, { data: { email, password } })).status()).toBe(401);
  expect((await request.post(`${api}/auth/login`, { data: { email, password: nextPassword } })).status()).toBe(200);
  const settings = await page.evaluate(() => localStorage.getItem('lifelikegame_appearance_v1'));
  expect(JSON.parse(settings!)).toEqual({ mode: 'dark', accent: 'purple' });
  expect(settings).not.toContain(password); expect(settings).not.toContain(nextPassword);
  expect(errors).toEqual([]);
});
